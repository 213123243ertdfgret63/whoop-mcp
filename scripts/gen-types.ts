#!/usr/bin/env bun
// Generates src/whoop/openapi.d.ts from WHOOP's published OpenAPI spec, without the Trusted Partner endpoints.
// openapi-typescript needs the TypeScript 5 JS API (TS 7 has none), so it runs via an isolated bunx install.
import { mkdtemp, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { WHOOP } from "../src/config.ts";

const spec = (await (await fetch(WHOOP.openapiUrl)).json()) as { paths: Record<string, unknown> };
const dropped = Object.keys(spec.paths).filter((p) => p.includes("/partner/"));
for (const p of dropped) delete spec.paths[p];

const dir = await mkdtemp(join(tmpdir(), "whoop-openapi-"));
const out = join(import.meta.dir, "..", "src", "whoop", "openapi.d.ts");
try {
  const specFile = join(dir, "openapi.json");
  await Bun.write(specFile, JSON.stringify(spec));
  const proc = Bun.spawn(["bunx", "openapi-typescript@7.13.0", specFile, "-o", join(dir, "out.d.ts")], { stdout: "inherit", stderr: "inherit" });
  if ((await proc.exited) !== 0) throw new Error("openapi-typescript failed");
  const header = `// Generated by scripts/gen-types.ts from ${WHOOP.openapiUrl} — do not edit.\n// Partner endpoints removed: ${dropped.length}.\n\n`;
  await Bun.write(out, header + (await Bun.file(join(dir, "out.d.ts")).text()));
} finally {
  await rm(dir, { recursive: true, force: true });
}
console.error(`Wrote ${out} (${Object.keys(spec.paths).length} paths, ${dropped.length} partner paths dropped).`);
